-- 1. TABELA DE INVOICES (Faturamento / Emissão de Notas Fiscais ao Cliente)
CREATE TABLE invoices 
    ( 
     invoice_id      NUMBER GENERATED BY DEFAULT AS IDENTITY 
        ( START WITH 1 NOCACHE )  NOT NULL , 
     project_id      NUMBER  NOT NULL , 
     invoice_number  VARCHAR2 (50)  NOT NULL , 
     issue_date      DATE  NOT NULL , 
     due_date        DATE  NOT NULL , 
     invoice_amount  NUMBER (12,2)  NOT NULL , 
     status          VARCHAR2 (30) DEFAULT 'Issued' NOT NULL 
    ) 
    LOGGING 
;

ALTER TABLE invoices 
    ADD CONSTRAINT pk_invoices PRIMARY KEY ( invoice_id ) ;

ALTER TABLE invoices 
    ADD CONSTRAINT uq_invoice_number UNIQUE ( invoice_number ) ;

-- 2. TABELA DE PAYMENTS RECEIVED (Entradas reais no Caixa - Medições Pagas)
CREATE TABLE payments_received 
    ( 
     payment_id      NUMBER GENERATED BY DEFAULT AS IDENTITY 
        ( START WITH 1 NOCACHE )  NOT NULL , 
     invoice_id      NUMBER  NOT NULL ,         -- Vinculado direto à nota emitida
     payment_date    DATE  NOT NULL ,           -- Quando o dinheiro caiu na conta
     amount_received NUMBER (12,2)  NOT NULL ,  -- Valor pago (pode ser parcial)
     payment_method  VARCHAR2 (50)  NOT NULL    -- Pix, Transferência, Boleto
    ) 
    LOGGING 
;

ALTER TABLE payments_received 
    ADD CONSTRAINT pk_payments_received PRIMARY KEY ( payment_id ) ;

-- 3. TABELA DE OPERATIONAL EXPENSES (Saídas reais do Caixa - Custos da Obra)
CREATE TABLE operational_expenses 
    ( 
     expense_id      NUMBER GENERATED BY DEFAULT AS IDENTITY 
        ( START WITH 1 NOCACHE )  NOT NULL , 
     project_id      NUMBER  NOT NULL ,         -- A qual obra esse custo pertence
     expense_type    VARCHAR2 (50)  NOT NULL ,  -- Material, Taxa, Equipamento, Terceirizados
     description     VARCHAR2 (255)  NOT NULL , -- Ex: "Compra de 50 sacos de cimento"
     expense_date    DATE  NOT NULL ,           -- Data do pagamento/desembolso
     expense_amount  NUMBER (12,2)  NOT NULL   -- Quanto custou
    ) 
    LOGGING 
;

ALTER TABLE operational_expenses 
    ADD CONSTRAINT pk_operational_expenses PRIMARY KEY ( expense_id ) ;

-- ===========================================================================
-- CHAVES ESTRANGEIRAS DO MÓDULO FINANCEIRO
-- ===========================================================================

-- Amarra as notas fiscais ao projeto operacional
ALTER TABLE invoices 
    ADD CONSTRAINT fk_invoices_projects FOREIGN KEY ( project_id ) 
    REFERENCES projects ( project_id ) ON DELETE CASCADE ;

-- Amarra os pagamentos recebidos à nota fiscal correspondente
ALTER TABLE payments_received 
    ADD CONSTRAINT fk_payments_invoices FOREIGN KEY ( invoice_id ) 
    REFERENCES invoices ( invoice_id ) ON DELETE CASCADE ;

-- Amarra as despesas operacionais ao projeto correspondente
ALTER TABLE operational_expenses 
    ADD CONSTRAINT fk_expenses_projects FOREIGN KEY ( project_id ) 
    REFERENCES projects ( project_id ) ON DELETE CASCADE ;

